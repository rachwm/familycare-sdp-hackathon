from __future__ import annotations

import argparse
import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)
from sklearn.model_selection import LeaveOneGroupOut


NON_FEATURE_COLUMNS = [
    "source_file",
    "subject",
    "activity",
    "class_name",
    "label",
]

# A lower threshold prioritizes fall detection.
# At 0.45, the current LOSO results provide a better balance
# between missed falls and unnecessary check-in prompts.
DECISION_THRESHOLD = 0.45


def create_model() -> RandomForestClassifier:
    """Create a conservative model for the small dataset."""
    return RandomForestClassifier(
        n_estimators=500,
        max_depth=6,
        min_samples_leaf=2,
        max_features="sqrt",
        class_weight="balanced",
        random_state=42,
        n_jobs=-1,
    )


def calculate_metrics(
    actual: np.ndarray,
    predicted: np.ndarray,
) -> dict:
    """Calculate safety-relevant classification metrics."""
    tn, fp, fn, tp = confusion_matrix(
        actual,
        predicted,
        labels=[0, 1],
    ).ravel()

    specificity = (
        tn / (tn + fp)
        if (tn + fp) > 0
        else 0.0
    )

    return {
        "accuracy": float(
            accuracy_score(actual, predicted)
        ),
        "balanced_accuracy": float(
            balanced_accuracy_score(actual, predicted)
        ),
        "fall_precision": float(
            precision_score(
                actual,
                predicted,
                zero_division=0,
            )
        ),
        "fall_recall": float(
            recall_score(
                actual,
                predicted,
                zero_division=0,
            )
        ),
        "fall_f1": float(
            f1_score(
                actual,
                predicted,
                zero_division=0,
            )
        ),
        "specificity": float(specificity),
        "true_negatives": int(tn),
        "false_positives": int(fp),
        "false_negatives": int(fn),
        "true_positives": int(tp),
    }


def print_metrics(
    title: str,
    metrics: dict,
) -> None:
    """Print one formatted metrics section."""
    print(f"\n{title}")
    print("-" * len(title))
    print(f"Accuracy:          {metrics['accuracy']:.3f}")
    print(
        f"Balanced accuracy: "
        f"{metrics['balanced_accuracy']:.3f}"
    )
    print(
        f"Fall precision:    "
        f"{metrics['fall_precision']:.3f}"
    )
    print(
        f"Fall recall:       "
        f"{metrics['fall_recall']:.3f}"
    )
    print(f"Fall F1:           {metrics['fall_f1']:.3f}")
    print(
        f"Specificity:       "
        f"{metrics['specificity']:.3f}"
    )
    print(
        f"True positives:    "
        f"{metrics['true_positives']}"
    )
    print(
        f"True negatives:    "
        f"{metrics['true_negatives']}"
    )
    print(
        f"False positives:   "
        f"{metrics['false_positives']}"
    )
    print(
        f"False negatives:   "
        f"{metrics['false_negatives']}"
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Train and evaluate the FamilyCare "
            "Random Forest fall detector."
        )
    )

    parser.add_argument(
        "--features",
        default="data/fall/fall_features.csv",
        help="CSV generated by feature_extractor.py",
    )

    parser.add_argument(
        "--model-output",
        default=(
            "fall_detection/models/"
            "fall_random_forest.joblib"
        ),
    )

    parser.add_argument(
        "--metrics-output",
        default=(
            "fall_detection/models/"
            "fall_model_metrics.json"
        ),
    )

    parser.add_argument(
        "--predictions-output",
        default=(
            "fall_detection/models/"
            "fall_oof_predictions.csv"
        ),
    )

    parser.add_argument(
        "--importance-output",
        default=(
            "fall_detection/models/"
            "fall_feature_importance.csv"
        ),
    )

    arguments = parser.parse_args()

    feature_path = Path(arguments.features)

    if not feature_path.exists():
        raise FileNotFoundError(
            f"Feature table not found: {feature_path}"
        )

    feature_table = pd.read_csv(feature_path)

    missing_metadata = [
        column
        for column in NON_FEATURE_COLUMNS
        if column not in feature_table.columns
    ]

    if missing_metadata:
        raise ValueError(
            f"Feature table is missing columns: "
            f"{missing_metadata}"
        )

    feature_columns = [
        column
        for column in feature_table.columns
        if column not in NON_FEATURE_COLUMNS
    ]

    X = feature_table[feature_columns].astype(float)
    y = feature_table["label"].astype(int).to_numpy()
    groups = (
        feature_table["subject"]
        .astype(str)
        .to_numpy()
    )

    if X.isna().any().any():
        raise ValueError(
            "Feature table contains missing values"
        )

    if set(np.unique(y)) != {0, 1}:
        raise ValueError(
            "Labels must contain both 0 and 1"
        )

    print(f"Recordings: {len(feature_table)}")
    print(f"Features: {len(feature_columns)}")
    print(f"Subjects: {sorted(np.unique(groups))}")
    print(f"Falls: {int(np.sum(y == 1))}")
    print(f"Non-falls: {int(np.sum(y == 0))}")
    print(
        f"Decision threshold: {DECISION_THRESHOLD:.2f}"
    )

    # Every recording is tested once on a model that has never
    # trained on that recording's participant.
    validator = LeaveOneGroupOut()

    out_of_fold_probabilities = np.zeros(
        len(feature_table),
        dtype=float,
    )

    out_of_fold_predictions = np.zeros(
        len(feature_table),
        dtype=int,
    )

    fold_results = []

    for fold_number, (
        train_indices,
        test_indices,
    ) in enumerate(
        validator.split(X, y, groups),
        start=1,
    ):
        held_out_subject = str(
            np.unique(groups[test_indices])[0]
        )

        fold_model = create_model()

        fold_model.fit(
            X.iloc[train_indices],
            y[train_indices],
        )

        fall_probabilities = (
            fold_model.predict_proba(
                X.iloc[test_indices]
            )[:, 1]
        )

        predictions = (
            fall_probabilities >= DECISION_THRESHOLD
        ).astype(int)

        out_of_fold_probabilities[
            test_indices
        ] = fall_probabilities

        out_of_fold_predictions[
            test_indices
        ] = predictions

        fold_metrics = calculate_metrics(
            y[test_indices],
            predictions,
        )

        fold_metrics["fold"] = fold_number
        fold_metrics[
            "held_out_subject"
        ] = held_out_subject
        fold_metrics[
            "test_recordings"
        ] = int(len(test_indices))

        fold_results.append(fold_metrics)

        print_metrics(
            (
                f"Fold {fold_number}: "
                f"Test {held_out_subject}"
            ),
            fold_metrics,
        )

    overall_metrics = calculate_metrics(
        y,
        out_of_fold_predictions,
    )

    print_metrics(
        "Overall leave-one-subject-out result",
        overall_metrics,
    )

    print("\nClassification report")
    print("---------------------")
    print(
        classification_report(
            y,
            out_of_fold_predictions,
            target_names=[
                "Not Fall",
                "Fall",
            ],
            digits=3,
            zero_division=0,
        )
    )

    print("Confusion matrix")
    print("----------------")
    print(
        confusion_matrix(
            y,
            out_of_fold_predictions,
            labels=[0, 1],
        )
    )

    # Save every subject-independent prediction.
    predictions_table = feature_table[
        [
            "source_file",
            "subject",
            "activity",
            "class_name",
            "label",
        ]
    ].copy()

    predictions_table[
        "fall_probability"
    ] = out_of_fold_probabilities

    predictions_table[
        "decision_threshold"
    ] = DECISION_THRESHOLD

    predictions_table[
        "predicted_label"
    ] = out_of_fold_predictions

    predictions_table["correct"] = (
        predictions_table["label"]
        == predictions_table["predicted_label"]
    )

    predictions_path = Path(
        arguments.predictions_output
    )

    predictions_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    predictions_table.to_csv(
        predictions_path,
        index=False,
    )

    # Train the final deployable model using all recordings.
    final_model = create_model()
    final_model.fit(X, y)

    model_bundle = {
        "model": final_model,
        "feature_names": feature_columns,
        "threshold": DECISION_THRESHOLD,
        "model_version": "random-forest-v1",
        "training_recordings": int(
            len(feature_table)
        ),
        "training_subjects": sorted(
            np.unique(groups).tolist()
        ),
        "overall_loso_metrics": overall_metrics,
    }

    model_path = Path(arguments.model_output)

    model_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    joblib.dump(
        model_bundle,
        model_path,
    )

    # Save feature importance for explanation to judges.
    importance_table = pd.DataFrame(
        {
            "feature": feature_columns,
            "importance": (
                final_model.feature_importances_
            ),
        }
    ).sort_values(
        by="importance",
        ascending=False,
    )

    importance_path = Path(
        arguments.importance_output
    )

    importance_table.to_csv(
        importance_path,
        index=False,
    )

    metrics_document = {
        "evaluation_method": (
            "Leave-One-Subject-Out cross-validation"
        ),
        "threshold": DECISION_THRESHOLD,
        "overall": overall_metrics,
        "folds": fold_results,
        "classification_report": (
            classification_report(
                y,
                out_of_fold_predictions,
                target_names=[
                    "Not Fall",
                    "Fall",
                ],
                output_dict=True,
                zero_division=0,
            )
        ),
    }

    metrics_path = Path(
        arguments.metrics_output
    )

    with metrics_path.open(
        "w",
        encoding="utf-8",
    ) as metrics_file:
        json.dump(
            metrics_document,
            metrics_file,
            indent=2,
        )

    print("\nTop 10 features")
    print("---------------")
    print(
        importance_table.head(10).to_string(
            index=False,
        )
    )

    print(
        f"\nSaved model: "
        f"{model_path.resolve()}"
    )

    print(
        f"Saved metrics: "
        f"{metrics_path.resolve()}"
    )

    print(
        f"Saved predictions: "
        f"{predictions_path.resolve()}"
    )

    print(
        f"Saved feature importance: "
        f"{importance_path.resolve()}"
    )


if __name__ == "__main__":
    main()